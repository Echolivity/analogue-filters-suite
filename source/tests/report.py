w("The gen~ code in the device is generated by `src/build_genexpr.py`. For testing, `tools/genexpr2c.py` parses that exact GenExpr text and translates it to C. "
  "The C is compiled and driven sample by sample by `tests/harness.c`. Parameter changes arrive at given sample positions, the same way Live's messages reach gen~. "
  "Every number below comes from running the shipping DSP code, not a separate model of it.\n")
w("The transpiler also acts as a static checker. It rejects undeclared names, block-scope violations, wrong argument or return counts, "
  "assignments to Params or function arguments, and any History read after it has been written in the same sample. "
  "It caught one real bug during development: a local variable that shadowed a Param.\n")
w("**Not covered by these tests** (they need Max/Live itself): Max's own gen~ compiler accepting the code, the device loading in Live, "
  "the UI appearance, Live's parameter and automation plumbing, MIDI mapping in Live, and device-bypass behaviour. See *Manual test checklist* at the end.\n")
